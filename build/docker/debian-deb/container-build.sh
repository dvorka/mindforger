# runs INSIDE the mindforger-deb-builder:<release> container - see
# build-deb.sh. expects the repository read-only mounted @ /src, an output
# dir @ /out, and MF_DEBIAN_RELEASE set (baked into the image, see Dockerfile).

set -euo pipefail

SRC=/src
OUT=/out
WORK=/build/work

MFVERSION=$(grep MINDFORGER_VERSION_STRING "${SRC}/lib/src/app_info.h" | sed -E 's/.*"([^"]+)".*/\1/')
MFFULLVERSION="${MFVERSION}-1"
MF="mindforger_${MFVERSION}"

echo "# Building MindForger ${MFVERSION} .deb for Debian ${MF_DEBIAN_RELEASE} ##################"

rm -rf "${WORK}"
mkdir -p "${WORK}/${MF}"
cd "${WORK}"

# copy sources, excluding VCS metadata, test trees not needed to package the
# binary, and any Makefile/object files left over from a host-side qmake
# build (a stale Makefile short-circuits qmake and gets self-regenerated by
# `make` with ITS OWN baked-in CONFIG, silently dropping any CONFIG+= applied
# below) - mirrors build/debian/debian-make-deb.sh's own pruning step
tar -C "${SRC}" \
    --exclude=.git \
    --exclude=app/test \
    --exclude=lib/test \
    --exclude=app/Makefile \
    --exclude=lib/Makefile \
    --exclude=app/mindforger \
    --exclude=.qmake.stash \
    --exclude='*.o' \
    --exclude='moc_*.cpp' \
    -cf - . | tar -C "${MF}" -xf -

cd "${MF}"

# build the vendored cmark-gfm dependency (static lib linked into lib/lib.pro)
# - drop any build/ dir copied in from the host checkout: its CMakeCache.txt
#   is tied to the host's absolute path and cmake refuses to reuse it here
echo -e "\n# Build dependency - cmark-gfm ###############################"
rm -rf deps/cmark-gfm/build
cmake -S deps/cmark-gfm -B deps/cmark-gfm/build \
    -DCMARK_TESTS=OFF -DCMARK_SHARED=OFF -DCMAKE_POLICY_VERSION_MINIMUM=3.5
cmake --build deps/cmark-gfm/build

# Debian packaging metadata + a changelog entry for this exact version. The
# checked-in build/debian/debian/{control,rules} target bullseye/bookworm
# (Qt WebKit) and are copied as-is for them. trixie dropped WebKit from the
# archive, so ONLY this throwaway copy is patched to Qt WebEngine instead -
# build/debian/debian itself is never touched by this script.
echo -e "\n# Debian packaging metadata ###################################"
cp -rf build/debian/debian .

if [ "${MF_DEBIAN_RELEASE}" = "trixie" ]; then
    echo "Patching packaging copy for trixie: Qt WebKit -> Qt WebEngine"
    sed -i 's/libqt5webkit5-dev/qtwebengine5-dev/' debian/control
    cat >> debian/rules <<'EOF'

# libqt5webkit5-dev is gone from Debian starting with trixie -> build with
# Qt WebEngine instead (see mindforger.pro's CONFIG+=mfwebengine option)
override_dh_auto_configure:
	dh_auto_configure -- CONFIG+=mfwebengine

# on a fresh source tree there is no generated Makefile to clean yet; letting
# dh_auto_clean run one anyway would make qmake regenerate it without the
# CONFIG above (the subdirs Makefiles re-invoke qmake with a fixed argument
# list, not the CONFIG+= passed to `make`), which re-selects the now
# unavailable WebKit modules and fails
override_dh_auto_clean:
EOF
fi

TS=$(date "+%a, %d %b %Y %H:%M:%S")
{
    echo "mindforger (${MFFULLVERSION}) unstable; urgency=low"
    echo " "
    echo "  * MindForger ${MFVERSION} release."
    echo " "
    echo " -- Martin Dvorak (Dvorka) <martin.dvorak@mindforger.com>  ${TS} +0000"
} > debian/changelog

# unsigned, binary-only build - fine for a package that is going to be
# uploaded to a GitHub release rather than into a signed apt repository
echo -e "\n# dpkg-buildpackage ############################################"
dpkg-buildpackage -us -uc -b

mkdir -p "${OUT}"
cp -v ../*.deb ../*.buildinfo ../*.changes "${OUT}/" 2>/dev/null || true

echo -e "\nDONE: package(s) written to /out"
ls -la "${OUT}"

# eof
